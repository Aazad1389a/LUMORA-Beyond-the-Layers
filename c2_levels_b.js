/* ---------------- validation (used by node test harness) ---------------- */
function validateLevels() {
  const problems = [];
  for (const L of LEVELS) {
    const tag = L.id;
    const inB = (x, y, w = 0, h = 0) => x >= 0 && y >= 0 && x + w <= L.w && y + h <= L.h;
    for (const s of L.solids) if (!inB(s[0], s[1], s[2], s[3])) problems.push(tag + ': solid out of bounds ' + s);
    for (const hz of L.hazards) if (!inB(hz[1], hz[2], hz[3], hz[4])) problems.push(tag + ': hazard OOB ' + hz);
    for (const mv of L.movers) {
      if (!inB(mv[0] + Math.max(0, mv[4]), mv[1] + Math.max(0, mv[5]), mv[2], mv[3]) ||
          !inB(mv[0] + Math.min(0, mv[4]), mv[1] + Math.min(0, mv[5]), mv[2], mv[3])) problems.push(tag + ': mover range OOB ' + mv);
    }
    for (const c of L.crystals) if (!inB(c[0], c[1])) problems.push(tag + ': crystal OOB ' + c);
    for (const e of L.enemies) if (!inB(e[1], e[2])) problems.push(tag + ': enemy OOB ' + e);
    if (L.crystals.length < 20) problems.push(tag + ': too few crystals (' + L.crystals.length + ')');
    if (L.orbs.length !== 1) problems.push(tag + ': needs exactly 1 orb');
    if (L.checkpoints.length < 2) problems.push(tag + ': needs >=2 checkpoints');
    if (!L.gate) problems.push(tag + ': missing gate');
    if (L.par < 60) problems.push(tag + ': par too small');
    // spawn must not start inside a solid of the starting layer
    const [sx, sy] = L.spawn;
    const spBox = { x: sx * T + 9, y: sy * T - 54, w: 30, h: 54 };
    for (const s of L.solids) {
      const lay = s[4];
      if (lay !== 'a' && lay !== 0 && lay !== 'c') continue;
      const r = { x: s[0] * T, y: s[1] * T, w: s[2] * T, h: s[3] * T };
      if (U.overlaps(spBox, r)) problems.push(tag + ': spawn inside solid ' + s);
    }
    // gate tile must be free-standing (not inside 'a' solid)
    const g = { x: L.gate[0] * T, y: (L.gate[1] - 1) * T, w: T, h: T };
    for (const s of L.solids) {
      if (s[4] !== 'a') continue;
      const r = { x: s[0] * T, y: s[1] * T, w: s[2] * T, h: s[3] * T };
      if (U.overlaps(g, r)) problems.push(tag + ': gate inside solid ' + s);
    }
    // crawlers must have ground beneath
    for (const e of L.enemies) {
      if (e[0] !== 'crawler') continue;
      const ex = e[1] * T + T / 2, ey = (e[2] + 1) * T;
      const hasGround = L.solids.some(s => {
        if (s[4] !== 'a' && s[4] !== 0) return false;
        const rx = s[0] * T, ry = s[1] * T, rw = s[2] * T, rh = s[3] * T;
        return ex >= rx - 4 && ex <= rx + rw + 4 && ry >= ey - 8 && ry <= ey + 60;
      });
      if (!hasGround) problems.push(tag + ': crawler without ground ' + e);
    }
    // sentries need a pedestal below (unless boss level area)
    for (const e of L.enemies) {
      if (e[0] !== 'sentry') continue;
      const ex = e[1] * T + T / 2, ey = (e[2] + 1) * T;
      const hasGround = L.solids.some(s => {
        if (s[4] === 'c') return false;
        const rx = s[0] * T, ry = s[1] * T, rw = s[2] * T, rh = s[3] * T;
        return ex >= rx && ex <= rx + rw && ry >= ey - 8 && ry <= ey + 60;
      });
      if (!hasGround) problems.push(tag + ': sentry without pedestal ' + e);
    }
  }
  return problems;
}
